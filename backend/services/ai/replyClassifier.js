/**
 * Classifies an Ollama response into one of four categories:
 *
 * 1. NATIVE_TOOL_CALL
 * 2. NORMAL_ANSWER
 * 3. FAKE_TOOL_JSON
 * 4. INVALID_RESPONSE
 */

export function classifyReply(response) {

    /*
     * --------------------------------------------------
     * 1. Check whether the response itself is valid.
     * --------------------------------------------------
     */
    if (!response || typeof response !== "object") {
        return {
            type: "INVALID_RESPONSE",
            reason: "Ollama returned an invalid response."
        };
    }


    /*
     * --------------------------------------------------
     * 2. Native Ollama tool call
     *
     * This is the REAL tool-calling format.
     * Example:
     *
     * response.tool_calls = [
     *   {
     *     function: {
     *       name: "get_monthly_summary",
     *       arguments: {
     *         month: "2026-10"
     *       }
     *     }
     *   }
     * ]
     * --------------------------------------------------
     */
    if (
        Array.isArray(response.tool_calls) &&
        response.tool_calls.length > 0
    ) {
        return {
            type: "NATIVE_TOOL_CALL",
            toolCalls: response.tool_calls
        };
    }


    /*
     * --------------------------------------------------
     * 3. Check the assistant's text content.
     * --------------------------------------------------
     */
    if (typeof response.content !== "string") {
        return {
            type: "INVALID_RESPONSE",
            reason: "Ollama response has no valid text content."
        };
    }


    const content = response.content.trim();


    /*
     * Empty content without a tool call is invalid.
     */
    if (content.length === 0) {
        return {
            type: "INVALID_RESPONSE",
            reason: "Ollama returned empty content."
        };
    }


    /*
     * --------------------------------------------------
     * 4. Detect fake JSON tool requests.
     *
     * Example of the problem we saw:
     *
     * {
     *   "name": "wikipedia",
     *   "parameters": {}
     * }
     *
     * This is NOT a native tool call.
     * It is just text generated by the model.
     * --------------------------------------------------
     */
    try {

        const parsed = JSON.parse(content);

        if (
            parsed &&
            typeof parsed === "object" &&
            !Array.isArray(parsed) &&
            (
                typeof parsed.name === "string" ||
                parsed.parameters !== undefined ||
                parsed.arguments !== undefined
            )
        ) {
            return {
                type: "FAKE_TOOL_JSON",
                content,
                parsed
            };
        }

    } catch {
        /*
         * Not JSON.
         * That is completely normal for a normal answer.
         */
    }


    /*
     * --------------------------------------------------
     * 5. Normal assistant answer.
     * --------------------------------------------------
     */
    return {
        type: "NORMAL_ANSWER",
        content
    };
}